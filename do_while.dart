
void main (){

/*
do while merupakan sebuah perulangan yang dilakukann setelah melakukan kondisi sebelumnya sama dengan while 
cuma bedanya kalo while itu perulangannya dilakukan dulu baru dieksekusi nah do while sebaliknya
*/
int number = 100;

do {
  print('number ke $number');
  number++;
} while(number<=10);
}